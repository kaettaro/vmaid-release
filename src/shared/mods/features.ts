/**
 * 機能 Mod のまとまり(ルールのノードが「このうちどれかが ON なら使える」とするための、仮の id)。Mod としては、存在しない。
 * 例: ゲームのトリガー・アクションは、どのゲームの Mod が ON でも出る。
 */
export const FEATURE_GROUPS: Readonly<Record<string, readonly string[]>> = {
  'game-any': ['game', 'game-connect4', 'game-reversi', 'game-chess']
}
const GROUP_NAMES: Readonly<Record<string, string>> = { 'game-any': 'ゲーム' }

/** 新規インストールで、最初から ON にする機能 Mod(2026-11 の公開ベータから。それ以外は、利用者が「Mod」タブで選ぶ) */
export const DEFAULT_ON_FEATURES: readonly string[] = ['chase', 'motion-tags']

const NAMES = new Map(FEATURE_MODS.map((m) => [m.id, m.name]))

/** 機能 Mod の表示名(不明な id は、そのまま返す) */
export function featureModName(id: string): string {
  return NAMES.get(id) ?? GROUP_NAMES[id] ?? id
}

export const isFeatureModId = (id: string): boolean => NAMES.has(id)
