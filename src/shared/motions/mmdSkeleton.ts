/** IK の定義(足 IK・つま先 IK) */
export interface MmdIk {
  /** IK ボーンの名前(VMD のキー・ON/OFF の名前と同じ) */
  bone: string
  /** 先端(この骨が、IK ボーンの位置に届くように、リンクの回転を決める) */
  target: string
  /** 繰り返しの回数 */
  loop: number
  /** 1 回の回転の上限(ラジアン) */
  limit: number
  /** 動かす骨(先端に近い順)。limits は X 軸まわりだけ動かす骨の回転範囲(MMD の符号のまま) */
  links: ReadonlyArray<{ bone: string; xRange?: readonly [min: number, max: number] }>
}

