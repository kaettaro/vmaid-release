/**
 * VRM のボーン ← MMD の骨(世界回転を取る骨)。親が先に並ぶ。
 * 下半身を hips にするのは、MMD の「下半身」が脚だけを回し、「上半身」は腰から別に回るため
 * (上半身の局所回転は、下半身の回転を打ち消した値になる)。腕の捩り・手捩は、ひじ・手首の世界回転に含まれる。
 */
export const MMD_TO_VRM: ReadonlyArray<readonly [vrm: string, mmd: string]> = [
  ['hips', '下半身'],
  ['spine', '上半身'],
  ['chest', '上半身2'],
  ['neck', '首'],
  ['head', '頭'],
  ['leftEye', '両目'],
  ['rightEye', '両目'],
  ...(['left', 'right'] as const).flatMap((side) => {
    const s = side === 'left' ? '左' : '右'
    return [
      [`${side}Shoulder`, `${s}肩`],
      [`${side}UpperArm`, `${s}腕`],
      [`${side}LowerArm`, `${s}ひじ`],
      [`${side}Hand`, `${s}手首`],
      ...FINGER_MAP.map(([m, v]) => [`${side}${v}`, `${s}${m}`] as const),
      [`${side}UpperLeg`, `${s}足`],
      [`${side}LowerLeg`, `${s}ひざ`],
      [`${side}Foot`, `${s}足首`],
      [`${side}Toes`, `${s}つま先`]
    ] as const
  })
]

